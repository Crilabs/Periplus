-- 1. Old pg-boss queues: their jobs and queue rows go (pgboss.delete_queue drops the jobs, a partition table if any,
--    the schedule and the queue row). The worker only creates and works the queues of config/queues.json.
DO $$
DECLARE
  old_queue text;
BEGIN
  IF to_regprocedure('pgboss.delete_queue(text)') IS NULL OR to_regclass('pgboss.queue') IS NULL THEN
    RETURN;
  END IF;
  FOREACH old_queue IN ARRAY ARRAY[
    'mentions.reread', 'mentions.batch', 'mentions.disambiguate', 'mentions.geocode',
    'discovery.area', 'discovery.tile', 'discovery.propose', 'discovery.place',
    'fetch.source', 'fetch.url', 'embed.chunks', 'sources.wikivoyage', 'compare.converters',
    'classify.document_version', 'extraction.mention', 'extraction.route', 'extraction.check',
    'consolidation.geo', 'consolidation.highlights', 'consolidation.summary', 'consolidation.followup',
    'revisit.freeze', 'places.website.freeze', 'quality.measure'
  ] LOOP
    IF EXISTS (SELECT 1 FROM pgboss.queue WHERE name = old_queue) THEN
      PERFORM pgboss.delete_queue(old_queue);
    END IF;
  END LOOP;
END $$;--> statement-breakpoint

-- 2. Protection triggers (design 7.2: only document_versions stays append-only): the delete guards, the history
--    recorders and the append-only guards of every table but document_versions, UPDATE/DELETE and TRUNCATE alike.
DO $$
DECLARE
  trg record;
BEGIN
  FOR trg IN
    SELECT c.relname AS table_name, tg.tgname AS trigger_name
    FROM pg_trigger tg
    JOIN pg_class c ON c.oid = tg.tgrelid
    JOIN pg_proc p ON p.oid = tg.tgfoid
    WHERE c.relnamespace = 'public'::regnamespace
      AND p.pronamespace = 'public'::regnamespace
      AND NOT tg.tgisinternal
      AND (p.proname IN ('forbid_delete', 'record_history')
           OR (p.proname = 'forbid_mutation' AND c.relname <> 'document_versions'))
  LOOP
    EXECUTE format('DROP TRIGGER %I ON public.%I', trg.trigger_name, trg.table_name);
  END LOOP;
END $$;--> statement-breakpoint

