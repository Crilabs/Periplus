import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/*
 * Bundles the browser scene of the place renderer (`lib/pipeline/images/scene/scene.ts` with three.js) into one
 * script and writes it as the string `SCENE_JS` to `scene.bundle.ts` (spec 13). The bundle is checked in, so the
 * worker image (production dependencies only) needs no esbuild; a test fails while it differs from what this script
 * builds. Run `npm run images:scene` after changing the scene or upgrading three.
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sceneDir = path.join(root, "lib", "pipeline", "images", "scene");
export const SCENE_BUNDLE_PATH = path.join(sceneDir, "scene.bundle.ts");

/** The source of `scene.bundle.ts`: the minified scene bundle as a string constant. */
export async function buildSceneBundle(): Promise<string> {
  const result = await build({
    entryPoints: [path.join(sceneDir, "scene.ts")],
    absWorkingDir: root,
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "inline",
    write: false,
    logLevel: "silent",
  });
  const code = result.outputFiles[0]!.text;
  return [
    "// Generated by scripts/build-render-scene.ts from scene.ts and three.js (npm run images:scene). Do not edit.",
    `export const SCENE_JS = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  void buildSceneBundle().then((source) => {
    writeFileSync(SCENE_BUNDLE_PATH, source);
    process.stdout.write(`${path.relative(root, SCENE_BUNDLE_PATH)}\n`);
  });
}
